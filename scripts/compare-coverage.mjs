// How often the compare tool's percentile intervals cover the truth at small n.
//
//   node scripts/compare-coverage.mjs   → docs/compare/coverage.md
//
// For each of the five firms with the most reports on the main build, draw 5
// and then 10 of its reports (without replacement), 500 times each, and set
// them against every other firm's reports at that build, as the tool would set
// a small firm against a large one. Each draw gets the tool's interval
// (percentile bootstrap, BOOTSTRAP_DRAWS resamples of the small firm's
// reports) for three gaps: the score's Hodges–Lehmann shift, and the ratio of
// "cites nothing" and of "claims more cause" rates per 100 claims. Coverage is
// the share of intervals that hold the firm's full-sample gap. The other side
// is held at its full sample: it is over a thousand reports, and what an
// interval misses at small n is the small side's spread. Real List rows only.
import { writeFileSync } from 'node:fs'
import { loadRows } from '../checks/lib/compare-run.mjs'
import { poolOf, countEditionsOnce } from '../src/list/compare/data.js'
import { hlShift, rng, hashString, percentileInterval, pooledRate } from '../src/list/compare/stats.js'
import { COMPARE_CONSTANTS as K } from '../src/list/compare/constants.js'

const REPS = 500
const SIZES = [5, 10]
const rows = loadRows()
const pool = poolOf(rows)
const builds = {}
for (const r of pool) builds[r.engine] = (builds[r.engine] || 0) + 1
const build = Object.entries(builds).sort((a, b) => b[1] - a[1])[0][0]
// As the tool compares them: city editions of one report count once.
const at = countEditionsOnce(pool.filter((r) => r.engine === build))
const sizes = {}
for (const r of at) sizes[r.company] = (sizes[r.company] || 0) + 1
const firms = Object.entries(sizes).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 5).map(([name]) => ({ name }))

const logRatio = (a, b, m) => {
  const ra = pooledRate(a.map((r) => ({ k: r[m], c: r.claims }))), rb = pooledRate(b.map((r) => ({ k: r[m], c: r.claims })))
  if (ra === 0 && rb === 0) return 0
  return Math.log(ra / rb)
}
const MEASURES = [
  ['Score (Hodges–Lehmann shift)', (a, b) => hlShift(a.map((r) => r.score), b.map((r) => r.score))],
  ['Cites nothing (rate ratio)', (a, b) => logRatio(a, b, 'unsupported')],
  ['Claims more cause (rate ratio)', (a, b) => logRatio(a, b, 'overreach')],
]

const out = []
const t0 = Date.now()
for (const f of firms) {
  const mine = at.filter((r) => r.company === f.name)
  const rest = at.filter((r) => r.company !== f.name)
  for (const n of SIZES) {
    const rand = rng(hashString(`coverage|${f.name}|${n}`))
    const hits = MEASURES.map(() => 0), widths = MEASURES.map(() => []), infinite = MEASURES.map(() => 0)
    const truth = MEASURES.map(([, fn]) => fn(mine, rest))
    for (let rep = 0; rep < REPS; rep++) {
      // n of the firm's reports, without replacement.
      const ix = mine.map((_, i) => i)
      for (let i = 0; i < n; i++) { const j = i + Math.floor(rand() * (ix.length - i)); [ix[i], ix[j]] = [ix[j], ix[i]] }
      const sub = ix.slice(0, n).map((i) => mine[i])
      const draws = MEASURES.map(() => new Float64Array(K.BOOTSTRAP_DRAWS))
      for (let d = 0; d < K.BOOTSTRAP_DRAWS; d++) {
        const re = Array.from({ length: n }, () => sub[Math.floor(rand() * n)])
        MEASURES.forEach(([, fn], k) => { draws[k][d] = fn(re, rest) })
      }
      MEASURES.forEach((_, k) => {
        const [lo, hi] = percentileInterval(Array.from(draws[k]))
        if (!Number.isFinite(lo) || !Number.isFinite(hi)) infinite[k]++
        if (lo <= truth[k] + 1e-12 && truth[k] - 1e-12 <= hi) hits[k]++
        widths[k].push(hi - lo)
      })
    }
    MEASURES.forEach(([label], k) => out.push({ firm: f.name, reports: mine.length, n, measure: label, coverage: hits[k] / REPS, infinite: infinite[k] / REPS,
      medianWidth: widths[k].filter(Number.isFinite).sort((a, b) => a - b)[Math.floor(widths[k].filter(Number.isFinite).length / 2)] }))
  }
}
const ms = Date.now() - t0
const pct = (x) => `${(100 * x).toFixed(1)}%`
const table = out.map((r) => `| ${r.firm} (${r.reports}) | ${r.n} | ${r.measure} | ${pct(r.coverage)} | ${r.infinite ? pct(r.infinite) : '0'} | ${r.medianWidth?.toFixed(2)} |`).join('\n')
const by = (n, m) => { const xs = out.filter((r) => r.n === n && r.measure === m).map((r) => r.coverage); return `${pct(Math.min(...xs))} to ${pct(Math.max(...xs))}` }
const summary = SIZES.flatMap((n) => MEASURES.map(([m]) => `- ${n} reports, ${m.toLowerCase()}: ${by(n, m)}`)).join('\n')
writeFileSync(new URL('../docs/compare/coverage.md', import.meta.url), `# Interval coverage at small n

Generated by \`node scripts/compare-coverage.mjs\` (${(ms / 1000).toFixed(0)} s) on the snapshot of The List,
build ${build}, with city editions of one report counted once, as the tool counts them. For each of
the five firms with the most reports, ${REPS} draws of 5 and then 10 of its
reports, each set against every other firm's reports at the build; the interval is the tool's 95%
percentile bootstrap (${K.BOOTSTRAP_DRAWS.toLocaleString('en-US')} resamples of the small side); coverage is the share holding the
firm's full-sample gap. Nominal: 95%. Ratios are compared on the log scale; an interval end is
infinite when some resample has no flagged claim of that kind.

Range across the five firms:

${summary}

| Firm (reports) | Drawn | Gap | Coverage | Infinite end | Median width |
|---|---|---|---|---|---|
${table}
`)
console.log(summary)
